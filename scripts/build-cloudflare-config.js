'use strict';

/**
 * Regenerates the Cloudflare Workers routing files from localization.config.js:
 * _redirects and _headers (Workers Static Assets) and src/locale-rules.json
 * (cookie and geo homepage redirects in src/worker.mjs).
 *
 * Usage: node scripts/build-cloudflare-config.js
 */
const fs = require('node:fs');
const path = require('node:path');
const localeConfig = require('../localization.config');

const root = path.join(__dirname, '..');
const GENERATED = 'generated by scripts/build-cloudflare-config.js, do not edit';
const defaultLocale = localeConfig.defaultLocale || 'en';
const pageNames = (pages) => (pages || []).map((page) => page.replace(/\.html$/, ''));
const LOCALIZED_SUBPAGES = pageNames(localeConfig.publicPages).filter((page) => page !== 'index');
const ENGLISH_ONLY_PAGES = pageNames(localeConfig.englishOnlyPages);
const localizedLocales = (localeConfig.publishedLocales || []).filter((code) => code !== defaultLocale);

const SECURITY_HEADERS = [
  ['X-Content-Type-Options', 'nosniff'],
  ['X-Frame-Options', 'SAMEORIGIN'],
  ['Referrer-Policy', 'strict-origin-when-cross-origin'],
  ['Permissions-Policy', 'camera=(), microphone=(), geolocation=()'],
  ['Strict-Transport-Security', 'max-age=31536000; includeSubDomains'],
];

function localeRules() {
  return {
    '//': GENERATED,
    cookieLocales: localizedLocales,
    countryLocales: { ...localeConfig.countryLocales },
    legacyRedirects: { ...localeConfig.legacyRedirects },
  };
}

function redirectsFile() {
  // Cloudflare requires static rules before dynamic (splat/placeholder) rules.
  const staticRules = [];
  const dynamicRules = [];
  for (const [legacy, published] of Object.entries(localeConfig.legacyRedirects || {})) {
    staticRules.push(`/${legacy} /${published} 308`);
    dynamicRules.push(`/${legacy}/* /${published}/:splat 308`);
  }
  staticRules.push('/privacy /privacy-policy 308');
  staticRules.push('/terms /terms-conditions 308');
  staticRules.push('/download / 308');
  dynamicRules.push('/:locale/download /:locale 308');
  for (const page of ENGLISH_ONLY_PAGES) dynamicRules.push(`/:locale/${page} /${page} 308`);

  return [
    `# ${GENERATED}`,
    '# Cookie and geo redirects on / live in src/worker.mjs. The www.hushbook.app',
    '# to apex rule from vercel.json is not reproduced: www has no DNS record.',
    ...staticRules,
    ...dynamicRules,
  ].join('\n') + '\n';
}

function headersFile() {
  const blocks = [
    ['/*', SECURITY_HEADERS],
    ['/assets/*', [['Cache-Control', 'public, max-age=31536000, immutable']]],
    // Asset-first requests never reach the Worker, so its workers.dev noindex
    // header needs this rule too.
    ['https://:worker.:subdomain.workers.dev/*', [['X-Robots-Tag', 'noindex, nofollow']]],
    ['/', [['Content-Language', defaultLocale]]],
  ];
  for (const page of [...LOCALIZED_SUBPAGES, ...ENGLISH_ONLY_PAGES]) {
    blocks.push([`/${page}`, [['Content-Language', defaultLocale]]]);
  }
  for (const locale of localizedLocales) {
    blocks.push([`/${locale}`, [['Content-Language', locale]]]);
    blocks.push([`/${locale}/*`, [['Content-Language', locale]]]);
  }

  const lines = [`# ${GENERATED}`, '# Responses built by src/worker.mjs (locale 307, tracking 308) do not get these.'];
  for (const [source, headers] of blocks) {
    lines.push('', source, ...headers.map(([name, value]) => `  ${name}: ${value}`));
  }
  return lines.join('\n') + '\n';
}

function render() {
  if (LOCALIZED_SUBPAGES.length) {
    throw new Error('Localized subpages need cookie/geo routing in src/routing.mjs and run_worker_first; only / is routed today.');
  }
  return {
    'src/locale-rules.json': `${JSON.stringify(localeRules(), null, 2)}\n`,
    _redirects: redirectsFile(),
    _headers: headersFile(),
  };
}

/** Parses _redirects into [{ source, destination, status }]. */
function parseRedirects(text) {
  return text.split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'))
    .map((line) => {
      const [source, destination, status = '302'] = line.split(/\s+/);
      return { source, destination, status: Number(status) };
    });
}

/** Parses _headers into Map(path -> { lower-case header name: value }). */
function parseHeaders(text) {
  const rules = new Map();
  let current = null;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    if (/^\s/.test(raw)) {
      const index = line.indexOf(':');
      current[line.slice(0, index).trim().toLowerCase()] = line.slice(index + 1).trim();
    } else {
      current = rules.get(line) || {};
      rules.set(line, current);
    }
  }
  return rules;
}

if (require.main === module) {
  for (const [file, content] of Object.entries(render())) {
    fs.writeFileSync(path.join(root, file), content);
    console.log(`Wrote ${file} (${content.split('\n').length - 1} lines)`);
  }
}

module.exports = { render, parseRedirects, parseHeaders };
